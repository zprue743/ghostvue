/**
 * Loads the TypeScript-authored sources that the `@ghostvue/mcp` asset bundle
 * (GHO-17 plan §4) copies: the docs corpus from the shared
 * `generateLlmsDocuments` and the executable example catalog.
 *
 * Both live in TypeScript modules that VitePress and Vitest load through Vite
 * (`apps/docs/.vitepress/*.ts` and `examples/registry.ts`, with extensionless
 * relative imports). Instead of duplicating their transforms in plain
 * JavaScript, this module imports them through Vite's module runner, the same
 * toolchain that already runs them for `pnpm docs:build`. It sits in the
 * workspace `scripts/lib` because Vite is a workspace-root tool; the MCP
 * package itself declares no build-time dependency on it.
 */
import { join } from 'node:path'

import { runnerImport } from 'vite'

import { writeComponentReferences } from './component-reference.js'

/**
 * @template T
 * @param {string} repositoryRoot
 * @param {string} relativePath
 * @returns {Promise<T>}
 */
async function importTypeScriptModule(repositoryRoot, relativePath) {
  const { module } = await runnerImport(join(repositoryRoot, relativePath), {
    root: repositoryRoot,
    // Only TypeScript stripping and resolution are needed; loading a project
    // Vite config would pull in unrelated plugins.
    configFile: false,
    envFile: false,
    logLevel: 'silent',
  })
  return /** @type {T} */ (module)
}

/**
 * Working drafts under `docs/plans/` are never searchable (GHO-17 plan §3.4,
 * decision M3), even when the sidebar links one for contributors.
 */
const EXCLUDED_SOURCE_PREFIX = 'docs/plans/'

/**
 * Builds the docs corpus pages with the same page set and transforms as
 * `llms-full.txt`: the pages linked from `docsSidebar`, in sidebar order,
 * minus `docs/plans/*` (GHO-17 plan §3.4). Expects `docs/reference/` to
 * exist already.
 *
 * @param {string} repositoryRoot
 * @returns {Promise<import('./mcp-asset-sources.js').DocsCorpusPage[]>}
 */
export async function buildDocsCorpusPages(repositoryRoot) {
  /** @type {typeof import('../../apps/docs/.vitepress/docs-nav')} */
  const nav = await importTypeScriptModule(
    repositoryRoot,
    'apps/docs/.vitepress/docs-nav.ts',
  )
  /** @type {typeof import('../../apps/docs/.vitepress/generate-llms-txt')} */
  const llms = await importTypeScriptModule(
    repositoryRoot,
    'apps/docs/.vitepress/generate-llms-txt.ts',
  )
  const { pages } = await llms.generateLlmsDocuments({
    docsRoot: join(repositoryRoot, 'docs'),
    title: nav.docsTitle,
    description: nav.docsDescription,
    sidebar: nav.docsSidebar,
  })
  return pages.filter(
    (page) => !page.sourcePath.startsWith(EXCLUDED_SOURCE_PREFIX),
  )
}

/**
 * Materializes the generated API reference pages (as `pnpm docs:build` does)
 * and then builds the docs corpus, so sidebar links under `/reference/`
 * resolve.
 *
 * @param {string} repositoryRoot
 */
export async function generateDocsCorpusPages(repositoryRoot) {
  await writeComponentReferences(repositoryRoot)
  return buildDocsCorpusPages(repositoryRoot)
}

/**
 * Reads the typed example catalog from `examples/registry.ts` (generated by
 * `pnpm registries:write`), in registry order.
 *
 * @param {string} repositoryRoot
 * @returns {Promise<import('./mcp-asset-sources.js').ExampleCatalogEntry[]>}
 */
export async function loadExampleCatalog(repositoryRoot) {
  /** @type {typeof import('../../examples/registry')} */
  const registry = await importTypeScriptModule(
    repositoryRoot,
    'examples/registry.ts',
  )
  return registry.ghostExamples.map(({ id, title, description, layer }) => ({
    id,
    title,
    description,
    layer,
  }))
}
